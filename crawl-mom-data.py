def fetch_baidu_hot():
    """百度热搜（真实接口），返回 [{'word': str, 'heat': int}]。"""
    data = _http_get_json(BAIDU_HOT_URL)
    out = []
    try:
        for card in data.get("data", {}).get("cards", []):
            for item in card.get("content", []):
                word = (item.get("word") or "").strip()
                heat = int(item.get("hotScore") or 0)
                if word:
                    out.append({"word": word, "heat": heat})
    except Exception:
        pass
    return out


def fetch_weibo_hot():
    """微博热搜（真实接口），返回 [{'word': str, 'heat': int}]。"""
    data = _http_get_json(WEIBO_HOT_URL)
    out = []
    try:
        for item in data.get("data", {}).get("realtime", []):
            word = (item.get("word") or "").strip()
            heat = int(item.get("num") or 0)
            if word:
                out.append({"word": word, "heat": heat})
    except Exception:
        pass
    return out


def is_mom_keyword(word):
    return any(k in word for k in MOM_KEYWORDS)



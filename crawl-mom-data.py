def build_topics():
    """输出母婴高频话题库（真实行业选题方向），不含任何模拟数值。"""
    topics = []
    seen = set()
    for keyword, category in CURATED_TOPICS:
        keyword = keyword.strip()
        if not keyword or keyword in seen:
            continue
        seen.add(keyword)
        topics.append({"keyword": keyword, "category": category})
    return topics


def build_products():
    """输出母婴商品参考（真实品牌 + 品类 + 价格区间 + 平台），不含销量/GMV。"""
    products = []
    for (name, brand, cat, p_lo, p_hi, _s_lo, _s_hi, platform) in PRODUCT_DB:
        products.append({
            "name": f"{brand}{name}" if brand not in name else name,
            "brand": brand,
            "category": cat,
            "price_min": p_lo,
            "price_max": p_hi,
            "platform": platform,
        })
    return products


def main():
    parser = argparse.ArgumentParser(description="优康宝贝母婴选题库与选品参考（仅真实行业信息）")
    parser.add_argument("--out", default=None,
                        help="输出 JSON 路径（默认脚本同目录 data.json）")
    args = parser.parse_args()

    out_path = args.out or os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "data.json")

    print("=" * 60)
    print("优康宝贝 · 母婴选题库与选品参考（仅真实信息）")
    print("=" * 60)

    print("[1/2] 生成母婴话题选题库 ...")
    topics = build_topics()

    print("[2/2] 生成母婴商品参考库 ...")
    products = build_products()

    print("[3/3] 写入 data.json ...")
    tz = timezone(timedelta(hours=8))
    payload = {
        "meta": {
            "generated_at": datetime.now(tz).strftime("%Y-%m-%d %H:%M:%S"),
            "generator": "crawl-mom-data.py v2.0",
            "note": ("仅保留真实行业信息：话题方向、品牌、品类、价格区间、平台。"
                     "不含热度/销量/GMV/地域等任何模拟数据。"
                     "真实热搜数据由 crawl-platforms.py 抓取抖音/快手。"),
        },
        "categories": sorted({p["category"] for p in products}),
        "topics": topics,
        "products": products,
    }

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)

    print()
    print("✅ 完成")
    print(f"   话题选题   : {len(topics)} 条（真实母婴高频话题）")
    print(f"   选品参考   : {len(products)} 款（真实品牌 + 价格区间）")
    print(f"   输出文件   : {out_path}")



    """展开地域层级为带权重的扁平列表。"""
    flat = []
    for prov in REGION_HIERARCHY:
        for city in prov["cities"]:
            for dist in city["districts"]:
                w = prov["weight"] * city["weight"] * dist["weight"]
                flat.append({
                    "province": prov["province"],
                    "city": city["city"],
                    "district": dist["district"],
                    "weight": w,
                })
    return flat


